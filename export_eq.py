#!/usr/bin/env python3
"""
export_eq.py  —  Real-time Windows EQ filters from your audiogram.

Generates, from audiogram.json, the artifacts needed to apply your per-ear
hearing compensation live (no re-encoding):

  * Stereo impulse-response WAVs (44.1 & 48 kHz) for foobar2000's convolver
    (left channel  = left-ear filter, right channel = right-ear filter).
  * An Equalizer APO config (per-ear GraphicEQ + Preamp) for system-wide
    compensation — Spotify / Tidal desktop, browser, games, everything.
  * A README with the install steps for both.

The filter is the exact same per-ear linear-phase design used by hearing_eq.py,
so what you hear in real time matches the rendered FLACs.

Requirements:
    pip install numpy scipy soundfile

Usage:
    python export_eq.py                          # uses ./audiogram.json
    python export_eq.py --strength 0.6 --out-dir filters
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

from hearing_eq import (
    load_loss_curves, boost_curve, design_eq_fir, _merge_curves,
    DEF_STRENGTH, DEF_MAX_BOOST, DEF_TAPS, SIM_STRENGTH, SIM_MAX_ATTEN,
)

DEF_RATES   = [44100, 48000]
SAFETY_DB   = 3.0   # headroom below 0 dBFS; covers bright broadband transients
                    # (peak freq-response normalization alone leaves ~1.3 dB of
                    #  summed-energy overshoot on worst-case material)


# ── filter assembly ───────────────────────────────────────────────────────────

def ear_filters(curves: dict) -> tuple[dict, dict]:
    """Return (left_loss, right_loss); missing ear falls back to the merged curve."""
    merged = _merge_curves(curves.get("left"), curves.get("right"))
    return curves.get("left") or merged, curves.get("right") or merged


def max_applied_boost(left: dict, right: dict, strength: float, max_boost: float) -> float:
    """Peak boost (dB) across both ears — drives the shared preamp / headroom."""
    vals = list(boost_curve(left, strength, max_boost).values()) \
         + list(boost_curve(right, strength, max_boost).values())
    return max(vals) if vals else 0.0


def build_ir(
    left: dict, right: dict, sr: int,
    strength: float, max_boost: float, numtaps: int, preamp_db: float,
    invert: bool = False,
) -> np.ndarray:
    """Stereo impulse response (N×2), preamp baked in equally on both channels."""
    fir_l = design_eq_fir(left,  sr, strength, max_boost, numtaps, invert)
    fir_r = design_eq_fir(right, sr, strength, max_boost, numtaps, invert)
    scale = 10.0 ** (preamp_db / 20.0)
    return np.stack([fir_l, fir_r], axis=1) * scale


# ── Equalizer APO config ──────────────────────────────────────────────────────

def graphic_eq_line(loss: dict, strength: float, max_boost: float) -> str:
    """One APO GraphicEQ line: 'f g; f g; …' anchored at 20 Hz and 20 kHz."""
    b   = boost_curve(loss, strength, max_boost)
    pts = sorted(b)
    lo, hi = pts[0], pts[-1]
    pairs = [(20, b[lo])] + [(f, b[f]) for f in pts] + [(20000, b[hi])]
    return "; ".join(f"{f} {g:.1f}" for f, g in pairs)


def apo_config(left: dict, right: dict, strength: float, max_boost: float,
               preamp_db: float) -> str:
    return (
        "# Hearing-compensation EQ — generated by export_eq.py\n"
        "# Per-ear GraphicEQ. The Preamp prevents clipping from the boost;\n"
        "# raise your system/app volume to compensate.\n"
        f"Preamp: {preamp_db:.1f} dB\n"
        "Channel: L\n"
        f"GraphicEQ: {graphic_eq_line(left, strength, max_boost)}\n"
        "Channel: R\n"
        f"GraphicEQ: {graphic_eq_line(right, strength, max_boost)}\n"
    )


# ── README ────────────────────────────────────────────────────────────────────

def readme_text(rates: list[int], preamp_db: float, strength: float) -> str:
    ir_list = "\n".join(f"      hearing_ir_{r}.wav   (use for {r/1000:g} kHz output)"
                        for r in rates)
    return f"""HEARING-COMPENSATION — REAL-TIME FILTERS FOR WINDOWS
=====================================================
Generated from audiogram.json  (strength {strength:g}, baked preamp {preamp_db:.1f} dB)

You have two independent options. Use foobar2000's convolver for local files
(bit-perfect, survives WASAPI exclusive / ASIO) and Equalizer APO for everything
else (Spotify, Tidal, browser, games).


1) foobar2000  (local files)
----------------------------
   a. Install the Convolver DSP component (foo_convolve / "Convolver").
      foobar2000 → File → Preferences → Components → Install…
   b. Preferences → Playback → DSP Manager: add "Convolver" to the active chain.
   c. Configure it and load the impulse that matches your output sample rate:
{ir_list}
      The preamp is already baked into the WAV, so leave the convolver gain at 0.
   d. If unsure of your rate, use the 44100 file; foobar will resample if needed.


2) Equalizer APO  (system-wide: Spotify / Tidal / browser / games)
------------------------------------------------------------------
   a. Install Equalizer APO and, when prompted, tick the output device you use
      (your headphones / DAC). Reboot.
   b. Open  C:\\Program Files\\EqualizerAPO\\config\\config.txt  and replace its
      contents with the contents of  equalizer_apo_config.txt  (in this folder).
      Or use the Peace GUI and import it.
   c. Done — the compensation now applies to all shared-mode audio on that device.

   NOTE: apps using WASAPI *exclusive* or ASIO bypass Equalizer APO. foobar2000
   in exclusive/ASIO is one such case — that's exactly why option 1 exists.


Simulation IRs (hearing_sim_*.wav)
----------------------------------
   These do the OPPOSITE: they attenuate the lost bands so a normal-hearing
   person hears the music the way the listener does. Load one in foobar2000's
   convolver (instead of hearing_ir_*) to demo your hearing to someone else.
   Remember to switch back afterwards.

Tuning
------
   Re-run with a different --strength to taste (0.5 = clinical half-gain;
   higher = brighter). Re-import / reload the new files afterwards.
"""


# ── CLI ───────────────────────────────────────────────────────────────────────

def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser(
        description="Export real-time Windows EQ filters (IR + Equalizer APO) "
                    "from an audiogram.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--audiogram", type=Path, default=Path("audiogram.json"),
                    metavar="FILE", help="audiogram.py JSON (default: ./audiogram.json)")
    ap.add_argument("--out-dir", type=Path, default=Path("windows_eq"),
                    metavar="DIR", help="output folder (default: ./windows_eq)")
    ap.add_argument("--strength", type=float, default=DEF_STRENGTH, metavar="F",
                    help=f"fraction of loss to compensate (default: {DEF_STRENGTH})")
    ap.add_argument("--max-boost", type=float, default=DEF_MAX_BOOST, metavar="DB",
                    help=f"ceiling on per-band boost (default: {DEF_MAX_BOOST})")
    ap.add_argument("--taps", type=int, default=DEF_TAPS, metavar="N",
                    help=f"FIR length (default: {DEF_TAPS})")
    ap.add_argument("--rates", type=int, nargs="+", default=DEF_RATES, metavar="HZ",
                    help=f"IR sample rates to export (default: {DEF_RATES})")
    return ap.parse_args()


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors="replace")
        except Exception:
            pass
    args = parse_args()

    ag = args.audiogram.resolve()
    if not ag.is_file():
        print(f"error: audiogram not found: {ag}", file=sys.stderr)
        return 1
    try:
        curves, baseline = load_loss_curves(ag)
    except Exception as e:
        print(f"error: cannot read audiogram: {e}", file=sys.stderr)
        return 1

    left, right = ear_filters(curves)
    peak    = max_applied_boost(left, right, args.strength, args.max_boost)
    preamp  = -(peak + SAFETY_DB)

    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)

    print(f"Audiogram: {ag.name}  baseline {baseline:.1f} dBFS  "
          f"strength {args.strength:g}  peak boost {peak:.1f} dB")
    for ear, loss in (("left", left), ("right", right)):
        b = boost_curve(loss, args.strength, args.max_boost)
        print(f"  {ear:>5}: " + "  ".join(f"{f}:{v:+.0f}" for f, v in sorted(b.items())))
    print(f"  baked preamp {preamp:.1f} dB (shared, preserves L/R balance)\n")

    # Compensation impulse responses, one per sample rate
    for sr in args.rates:
        ir = build_ir(left, right, sr, args.strength, args.max_boost, args.taps, preamp)
        path = out / f"hearing_ir_{sr}.wav"
        sf.write(str(path), ir.astype(np.float32), sr, subtype="FLOAT")
        print(f"  wrote {path.name}  ({ir.shape[0]} taps, stereo float)")

    # Simulation impulse responses: attenuate the lost bands so a
    # normal-hearing person hears the music the way the listener does.
    # Attenuation-only → no headroom/preamp needed.
    for sr in args.rates:
        ir = build_ir(left, right, sr, SIM_STRENGTH, SIM_MAX_ATTEN, args.taps,
                      preamp_db=0.0, invert=True)
        path = out / f"hearing_sim_{sr}.wav"
        sf.write(str(path), ir.astype(np.float32), sr, subtype="FLOAT")
        print(f"  wrote {path.name}  (simulation — how the listener hears)")

    # Equalizer APO config
    cfg = out / "equalizer_apo_config.txt"
    cfg.write_text(apo_config(left, right, args.strength, args.max_boost, preamp),
                   encoding="utf-8")
    print(f"  wrote {cfg.name}")

    # README
    rdm = out / "README.txt"
    rdm.write_text(readme_text(args.rates, preamp, args.strength), encoding="utf-8")
    print(f"  wrote {rdm.name}")

    print(f"\nDone → {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
